#!/usr/bin/env python3
"""Emit typed recorder declarations/dispatch from the unchanged guest ABI."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
NAMES_MISSING = {
    'glClampColorARB', 'glUniform1uiv', 'glUniform2uiv', 'glUniform3uiv',
    'glUniform4uiv', 'glUniformMatrix2x3fv', 'glUniformMatrix2x4fv',
    'glUniformMatrix3x2fv', 'glUniformMatrix3x4fv', 'glUniformMatrix4x2fv',
    'glUniformMatrix4x3fv',
}
FIRE = set('''glActiveTexture glAlphaFunc glBindFramebuffer glBindTexture
glBlendFuncSeparate glClear glClearColor glClearDepth glCullFace glDepthFunc
glDisableVertexAttribArray glEnable glEnableVertexAttribArray
glFramebufferRenderbuffer glFramebufferTexture2D glTexParameteri glUniform1i
glUseProgram glVertexAttribPointer glViewport'''.split())
FENCES = set('''glAttachShader glCompileShader glCreateProgram glDeleteProgram
glDeleteShader glLinkProgram glShaderSource'''.split())
CUSTOM = set('''glBindRenderbuffer glDeleteRenderbuffers glGenRenderbuffers
glRenderbufferStorage glGetRenderbufferParameteriv glGetAttribLocation
glGetUniformLocation glCheckFramebufferStatus glDrawElements'''.split())
# Record-side attribute shadow, in guest call order, for draw snapshots.
NOTES = {
    'glEnableVertexAttribArray': 'record_note_attrib_enable(index, 1);',
    'glDisableVertexAttribArray': 'record_note_attrib_enable(index, 0);',
    'glVertexAttribPointer': 'record_note_attrib_pointer(index, size, type, normalized, stride, pointer);',
}
COPY = {'glDeleteFramebuffers': ('n', 'framebuffers', 4),
        'glDeleteTextures': ('n', 'textures', 4)}
for n in range(1, 5):
    for scalar in ('f', 'i'):
        COPY[f'glUniform{n}{scalar}v'] = ('count', 'value', n * 4)
for n in (2, 3, 4):
    COPY[f'glUniformMatrix{n}fv'] = ('count', 'value', n * n * 4)


def emit():
    source = (ROOT / 'recomp/runtime/gl_surface_generated.h').read_text()
    entries = re.findall(r'^\s+(\w+) \(\*(gl\w+)\)\(([^\n]*)\);', source, re.M)
    assert len(entries) == 73
    assert {name for _, name, _ in entries} >= FIRE | FENCES | CUSTOM | NAMES_MISSING | COPY.keys()
    out = ['/* Generated by recomp/vita/gl_record_surface.py. Do not edit. */',
           '_Static_assert(GUEST_GL_SURFACE_COUNT == 73u, "re-audit recorder ABI");',
           'enum IsaacGlRecordOpcode {']
    for i, (_, name, _) in enumerate(entries, 1):
        out.append(f'    REC_{name} = {i},')
    out += ['    REC_NATIVE_BIND_RBO, REC_NATIVE_STORE_RBO,',
            '    REC_NATIVE_DELETE_RBO, REC_NATIVE_GEN_RBO, REC_WORKER_CALL', '};']
    for ret, name, params in entries:
        args = [] if params == 'void' else [p.strip().split() for p in params.split(',')]
        assert all(len(a) == 2 for a in args)
        fields = '\n'.join(f'    {t} {p};' for t, p in args) or '    uint32_t unused;'
        out += [f'typedef struct Record_{name} {{', fields, f'}} Record_{name};']
        if name in CUSTOM or name in NAMES_MISSING:
            continue
        values = ', '.join(p for _, p in args) or '0u'
        out += [f'static {ret} record_{name}({params})', '{',
                f'    Record_{name} a = {{{values}}};']
        if name in FENCES:
            out.append('    isaac_gl_record_locations_reset(&s_locations);')
        if name in NOTES:
            out.append('    ' + NOTES[name])
        if name in ('glFramebufferRenderbuffer', 'glDeleteTextures', 'glDeleteFramebuffers', 'glGenFramebuffers'):
            out.append('    record_forget_status();')
        if name in COPY:
            count, pointer, stride = COPY[name]
            out += [f'    uint32_t bytes = record_client_bytes({count}, {stride}u, {pointer});',
                    f'    if (bytes && record_readable({pointer}, bytes)) {{',
                    f'        record_enqueue(REC_{name}, &a, sizeof a, {pointer}, bytes);',
                    '        return;', '    }']
        if name == 'glBindFramebuffer':
            out.append('    record_note_bind_fbo(target, framebuffer);')
        if name == 'glFramebufferTexture2D':
            out.append('    record_note_attach_fbo(target, attachment, textarget, texture, level);')
        if name in FIRE:
            out.append(f'    record_enqueue(REC_{name}, &a, sizeof a, 0u, 0u);')
        else:
            out += [f'    record_enqueue(REC_{name}, &a, sizeof a, 0u, 0u);',
                    '    record_sync();']
            if ret != 'void':
                out.append(f'    return ({ret})s_result;')
        out += ['}']
    out += ['static void record_dispatch(const IsaacGlRecordHeader *h, const void *payload)',
            '{', '    switch (h->opcode) {']
    for ret, name, params in entries:
        if name in NAMES_MISSING or name in CUSTOM - {'glGetAttribLocation', 'glGetUniformLocation', 'glCheckFramebufferStatus'}:
            continue
        args = [] if params == 'void' else [p.strip().split() for p in params.split(',')]
        out += [f'    case REC_{name}: {{',
                f'        Record_{name} a = *(const Record_{name} *)payload;']
        if not args:
            out.append('        (void)a;')
        pointer = COPY.get(name, (None, None, None))[1]
        if name in ('glGetAttribLocation', 'glGetUniformLocation'):
            pointer = 'name'
        if pointer:
            out += [f'        if (h->payload_bytes > sizeof a)',
                    f'            a.{pointer} = (guest_gl_addr)(uintptr_t)((const uint8_t *)payload + sizeof a);']
        actual = ', '.join('a.' + p for _, p in args)
        call = f's_target.{name}({actual})'
        out += [f'        s_result = (uint32_t){call};' if ret != 'void' else f'        {call};',
                '        break;', '    }']
    out += ['    default: record_custom_replay(h, payload); break;', '    }', '}']
    out += ['static void record_table(guest_gl_backend *backend)', '{']
    for _, name, _ in entries:
        if name not in NAMES_MISSING:
            out.append(f'    if (backend->{name}) backend->{name} = record_{name};')
    out += ['}', '']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    destination = ROOT / 'recomp/runtime/gl_record_surface.inc'
    text = emit()
    if args.write:
        destination.write_text(text, newline='\n')
    else:
        assert destination.read_text() == text, 'recorder surface is stale; regenerate'
    print('PASS recorder ABI generation: 73 typed entries, 11 unsupported unchanged')


if __name__ == '__main__':
    main()
