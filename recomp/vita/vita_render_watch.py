#!/usr/bin/env python3
"""Coverage ids for the render watch list (ISAAC_VITA_PROFILE_FUNCTION_ENTRY_CENSUS).

Reads the watch list (recomp/runtime/kage_vita_render_watch.h, one X(0x........u)
per entry) and the guest_coverage.json of the corpus being compiled, and writes
guest_entry_census_ids.h: the entry count, the corpus identity the ids were taken
from, the RVA table in watch order and a switch from coverage function id to
census slot.  CMake runs it at configure time with the knob ON, so the ids always
come from the corpus the eboot is built from (gen_all.py freezes the id space by
COVERAGE_FUNCTION_RVAS_SHA256, gen_all.py:1036, and refuses a corpus whose sorted
canonical roots hash differently, gen_all.py:17062).

  python vita_render_watch.py --watch kage_vita_render_watch.h \
      --coverage GENERATED/guest_coverage.json --output OUT/guest_entry_census_ids.h
  python vita_render_watch.py --watch ... --coverage ... --check   (no output file)

Exit 1 with a message on: a malformed or duplicate entry, more than 64 entries,
an RVA that is not a coverage function, a coverage file whose function list does
not hash to its own function_rvas_sha256, or ids that are not positions in the
sorted RVA list (the gen_all.py rule).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import sys
from pathlib import Path

WATCH_MAX = 64
RE_ENTRY = re.compile(r"^\s*X\((0x[0-9a-fA-F]{8})u\)")
RE_MACRO = re.compile(r"#define\s+KAGE_VITA_RENDER_WATCH\(X\)")


class WatchError(Exception):
    pass


def read_watch(path: Path) -> list[int]:
    text = path.read_text(encoding="utf-8")
    if not RE_MACRO.search(text):
        raise WatchError(f"{path}: no '#define KAGE_VITA_RENDER_WATCH(X)'")
    body = text[RE_MACRO.search(text).end():]
    rvas = []
    for line in body.splitlines():
        m = RE_ENTRY.match(line)
        if m:
            rvas.append(int(m.group(1), 16))
        if not line.rstrip().endswith("\\"):
            break  # the macro ends at the first line without a continuation
    if not rvas:
        raise WatchError(f"{path}: the watch list is empty")
    if len(rvas) > WATCH_MAX:
        raise WatchError(f"{path}: {len(rvas)} entries, at most {WATCH_MAX}")
    dup = sorted({r for r in rvas if rvas.count(r) > 1})
    if dup:
        raise WatchError(f"{path}: duplicate entries " + ", ".join(f"0x{r:08x}" for r in dup))
    return rvas


def rows_sha256(rvas) -> str:
    """gen_all.py _coverage_u32_rows_sha256 for one-column rows (checked in main)."""
    h = hashlib.sha256()
    for rva in rvas:
        h.update(struct.pack("<I", rva))
    return h.hexdigest()


def load_coverage(path: Path) -> tuple[dict, dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    functions = data.get("functions")
    if not isinstance(functions, list) or not functions:
        raise WatchError(f"{path}: no functions[]")
    by_rva = {}
    for f in functions:
        by_rva[int(f["rva"])] = int(f["id"])
    ordered = sorted(by_rva)
    if [by_rva[r] for r in ordered] != list(range(len(ordered))) or len(ordered) != len(functions):
        raise WatchError(f"{path}: function ids are not positions in the sorted RVA list")
    if data.get("function_count") != len(functions):
        raise WatchError(f"{path}: function_count {data.get('function_count')} != {len(functions)} rows")
    return data, by_rva


def render(rvas: list[int], ids: list[int], data: dict, sources: tuple[str, str]) -> str:
    out = [
        "/* GENERATED by recomp/vita/vita_render_watch.py -- do not edit.",
        f" * watch list: {sources[0]}",
        f" * coverage:   {sources[1]} */",
        "#ifndef GUEST_ENTRY_CENSUS_IDS_H",
        "#define GUEST_ENTRY_CENSUS_IDS_H",
        "",
        "#include <stdint.h>",
        "",
        f"#define GUEST_ENTRY_CENSUS_COUNT {len(rvas)}U",
        f"#define GUEST_ENTRY_CENSUS_GENERATION_ID \"{data.get('generation_id', '')}\"",
        f"#define GUEST_ENTRY_CENSUS_FUNCTION_RVAS_SHA256 \"{data.get('function_rvas_sha256', '')}\"",
        "/* The id space: the sampler checks both against guest_coverage_generated.h",
        " * (count at compile time, RVA hash at start-up). */",
        f"#define GUEST_ENTRY_CENSUS_FUNCTION_COUNT {data['function_count']}U",
        "/* Census slot order = watch order. */",
        "#define GUEST_ENTRY_CENSUS_RVAS { \\",
    ]
    for i in range(0, len(rvas), 6):
        part = ", ".join(f"0x{r:08x}U" for r in rvas[i:i + 6])
        out.append(f"    {part}, \\")
    out += [
        "}",
        "",
        "/* Coverage function id -> census slot, UINT32_MAX for an unwatched id.",
        " * Every generated body passes a constant id, so this folds to one",
        " * increment or to nothing. */",
        "static inline uint32_t guest_entry_census_slot(uint32_t id)",
        "{",
        "    switch (id) {",
    ]
    for slot, (rva, cid) in enumerate(zip(rvas, ids)):
        out.append(f"    case {cid}U: return {slot}U;  /* 0x{rva:08x} */")
    out += [
        "    default: return UINT32_MAX;",
        "    }",
        "}",
        "",
        "#endif",
        "",
    ]
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--watch", type=Path, required=True)
    ap.add_argument("--coverage", type=Path, required=True)
    ap.add_argument("--output", type=Path)
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    a = ap.parse_args(argv)
    if not a.check and a.output is None:
        ap.error("--output is required without --check")
    try:
        rvas = read_watch(a.watch)
        data, by_rva = load_coverage(a.coverage)
        got = rows_sha256(sorted(by_rva))
        want = data.get("function_rvas_sha256")
        if got != want:
            raise WatchError(f"{a.coverage}: sorted function RVAs hash to {got}, "
                             f"the file says function_rvas_sha256={want}")
        missing = [r for r in rvas if r not in by_rva]
        if missing:
            raise WatchError("not coverage functions in this corpus: " +
                             ", ".join(f"0x{r:08x}" for r in missing))
        ids = [by_rva[r] for r in rvas]
        if 0 in ids:  # guest_entry_census.h maps an empty hook argument to id 0
            raise WatchError("coverage id 0 cannot be watched (it is the empty-argument hook)")
    except (OSError, ValueError, KeyError, WatchError) as exc:
        print(f"vita_render_watch: FAIL {exc}", file=sys.stderr)
        return 1
    text = render(rvas, ids, data, (a.watch.name, a.coverage.name))
    if not a.check:
        a.output.parent.mkdir(parents=True, exist_ok=True)
        old = a.output.read_text(encoding="utf-8") if a.output.exists() else None
        if old != text:  # keep the mtime when nothing changed (no corpus-wide rebuild)
            a.output.write_text(text, encoding="utf-8", newline="\n")
    print(f"entries={len(rvas)} ids={min(ids)}..{max(ids)} "
          f"rvas_sha256={data['function_rvas_sha256'][:16]} generation={data.get('generation_id', '')[:20]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
